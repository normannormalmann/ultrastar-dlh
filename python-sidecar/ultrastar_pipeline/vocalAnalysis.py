"""Analyze existing audio without transcription, alignment, or changing notes."""
import argparse
import json
from importlib.metadata import version
from pathlib import Path
from shutil import copyfile

from .cache import atomic_write_bytes, audio_fingerprint
from .pitch import track_pitch
from .separate import separate
from .verarbeitung import _waehle_device


def analyze(audio: Path, output: Path, cache: Path, device: str, offset: int):
    fingerprint = audio_fingerprint(audio)
    vocals = separate(audio, cache, fingerprint, device)
    points = track_pitch(vocals, cache, fingerprint, device)
    output.mkdir(parents=True, exist_ok=True)
    copyfile(vocals, output / "vocals.wav")
    trace = {"midiOffset": offset, "points": [
        {"ms": round(p.time * 1000, 3), "pitch": p.midi - offset}
        for p in points if p.voiced
    ]}
    atomic_write_bytes(output / "originalPitch.json", json.dumps(trace).encode("utf8"))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--audio", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--work-dir", type=Path, required=True)
    parser.add_argument("--device", choices=["auto", "cpu", "cuda"], default="auto")
    parser.add_argument("--offset", type=int, choices=[48, 60], default=60)
    args = parser.parse_args()
    # Package upgrades must not reuse results generated by a different model stack.
    packages = "-".join(version(name) for name in ("demucs", "torch", "swift-f0"))
    analyze(args.audio, args.out, args.work_dir / packages, _waehle_device(args.device, []), args.offset)


if __name__ == "__main__":
    main()
